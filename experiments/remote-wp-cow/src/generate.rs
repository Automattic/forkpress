#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{LocalDb, Manifest, Probe, RemoteDbTunnel, MANIFEST_VERSION};

    fn manifest() -> Manifest {
        Manifest {
            version: MANIFEST_VERSION,
            name: "example".to_string(),
            ssh: "user@example.com".to_string(),
            remote_path: "/srv/www".to_string(),
            remote_url: "https://example.com".to_string(),
            local_url: "http://example.test".to_string(),
            created_at_unix: 1,
            probe: Probe {
                table_prefix: "wp_".to_string(),
                db_name: "example_wp".to_string(),
                db_host: "localhost".to_string(),
                db_user: "example_wp".to_string(),
                ..Probe::default()
            },
            local_db: LocalDb {
                name: "cow_example".to_string(),
                user: "cow_example".to_string(),
                password: "secret".to_string(),
                host: "127.0.0.1".to_string(),
                port: 33071,
            },
            remote_db_tunnel: RemoteDbTunnel {
                host: "127.0.0.1".to_string(),
                port: 33072,
            },
            control_url: "http://127.0.0.1:39070".to_string(),
            cache_max_file_bytes: 1024,
            remote_metadata_cache_ttl_secs: 30,
        }
    }

    #[test]
    fn generated_config_shadows_urls_and_database() {
        let php = wp_config_php(&manifest());
        assert!(php.contains("define( 'DB_NAME',     'cow_example' );"));
        assert!(php.contains("define( 'WP_HOME',    'http://example.test' );"));
        assert!(php.contains("$table_prefix = 'wp_';"));
        assert!(php.contains("WPCOW_CONTROL_URL"));
        assert!(php.contains("WPCOW_REMOTE_DB_HOST"));
    }

    #[test]
    fn db_dropin_blocks_write_classes() {
        let php = db_dropin_php();
        assert!(php.contains("cow_is_write_sql"));
        assert!(php.contains("/materialize"));
        assert!(php.contains("cow_remote_mysqli"));
    }

    #[test]
    fn safety_plugin_blocks_side_effects() {
        let php = safety_mu_plugin_php();
        assert!(php.contains("pre_wp_mail"));
        assert!(php.contains("X-Robots-Tag"));
        assert!(php.contains("pre_http_request"));
    }
}
