use anyhow::Result;
use std::fs;
use std::path::Path;

use crate::config::{ClonePaths, Manifest};

pub fn write_wordpress_overrides(paths: &ClonePaths, manifest: &Manifest) -> Result<()> {
    fs::create_dir_all(paths.upper.join("wp-content/mu-plugins"))?;
    fs::write(paths.upper.join("wp-config.php"), wp_config_php(manifest))?;
    fs::write(paths.upper.join("wp-content/db.php"), db_dropin_php())?;
    fs::write(
        paths.upper.join("wp-content/mu-plugins/wp-cow-safety.php"),
        safety_mu_plugin_php(),
    )?;
    fs::write(paths.generated.join("router.php"), router_php())?;
    Ok(())
}

pub fn wp_config_php(manifest: &Manifest) -> String {
    format!(
        r#"<?php
/**
 * Generated by wp-cow. This file intentionally shadows the remote wp-config.php.
 */

define( 'DB_NAME',     {local_db_name} );
define( 'DB_USER',     {local_db_user} );
define( 'DB_PASSWORD', {local_db_password} );
define( 'DB_HOST',     {local_db_host} );

define( 'WP_HOME',    {local_url} );
define( 'WP_SITEURL', {local_url} );

$table_prefix = {table_prefix};

define( 'WPCOW_CLONE',       {clone_name} );
define( 'WPCOW_CONTROL_URL', {control_url} );
define( 'WPCOW_REMOTE_DB_NAME',     {remote_db_name} );
define( 'WPCOW_REMOTE_DB_USER',     {remote_db_user} );
define( 'WPCOW_REMOTE_DB_PASSWORD', {remote_db_password} );
define( 'WPCOW_REMOTE_DB_HOST',     {remote_db_host} );

define( 'FS_METHOD', 'direct' );
define( 'DISABLE_WP_CRON', true );

if ( ! defined( 'ABSPATH' ) ) {{
	define( 'ABSPATH', __DIR__ . '/' );
}}

require_once ABSPATH . 'wp-settings.php';
"#,
        local_db_name = php_string(&manifest.local_db.name),
        local_db_user = php_string(&manifest.local_db.user),
        local_db_password = php_string(&manifest.local_db.password),
        local_db_host = php_string(&format!(
            "{}:{}",
            manifest.local_db.host, manifest.local_db.port
        )),
        local_url = php_string(&manifest.local_url),
        table_prefix = php_string(&manifest.probe.table_prefix),
        clone_name = php_string(&manifest.name),
        control_url = php_string(&manifest.control_url),
        remote_db_name = php_string(&manifest.probe.db_name),
        remote_db_user = php_string(&manifest.probe.db_user),
        remote_db_password = php_string(&manifest.probe.db_password),
        remote_db_host = php_string(&format!(
            "{}:{}",
            manifest.remote_db_tunnel.host, manifest.remote_db_tunnel.port
        )),
    )
}

pub fn db_dropin_php() -> &'static str {
    r#"<?php
/**
 * Generated by wp-cow. Routes safe reads to the daemon and keeps writes local.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

if ( ! class_exists( 'wpdb' ) ) {
	require_once ABSPATH . WPINC . '/class-wpdb.php';
}

function cow_is_write_sql( $sql ) {
	$sql = ltrim( preg_replace( '/^\s*(?:\/\*.*?\*\/\s*|--[^\n]*\n\s*|#[^\n]*\n\s*)*/s', '', $sql ) );
	return (bool) preg_match( '/^(INSERT|UPDATE|DELETE|REPLACE|ALTER|CREATE|DROP|TRUNCATE|RENAME|LOAD|LOCK|UNLOCK|GRANT|REVOKE|OPTIMIZE|ANALYZE|REPAIR)\b/i', $sql );
}

function cow_is_safe_read_sql( $sql ) {
	$sql = ltrim( preg_replace( '/^\s*(?:\/\*.*?\*\/\s*|--[^\n]*\n\s*|#[^\n]*\n\s*)*/s', '', $sql ) );
	return (bool) preg_match( '/^(SELECT|SHOW|DESCRIBE|DESC|EXPLAIN)\b/i', $sql );
}

function cow_tables_from_sql( $sql ) {
	$tables = array();
	if ( preg_match_all( '/\b(?:FROM|JOIN|UPDATE|INTO|TABLE)\s+`?([A-Za-z0-9_$]+)`?/i', $sql, $matches ) ) {
		foreach ( $matches[1] as $table ) {
			$tables[ $table ] = true;
		}
	}
	if ( preg_match_all( '/\bUPDATE\s+(?:LOW_PRIORITY\s+)?(?:IGNORE\s+)?`?([A-Za-z0-9_$]+)`?/i', $sql, $matches ) ) {
		foreach ( $matches[1] as $table ) {
			$tables[ $table ] = true;
		}
	}
	return array_keys( $tables );
}

function cow_control_timeout_secs() {
	$timeout = (int) getenv( 'WPCOW_CONTROL_REQUEST_TIMEOUT_SECS' );
	if ( $timeout < 1 ) {
		$timeout = 15;
	}
	return $timeout;
}

function cow_control_request( $path, $payload ) {
	$payload['clone'] = WPCOW_CLONE;
	$url = rtrim( WPCOW_CONTROL_URL, '/' ) . $path;
	$body = json_encode( $payload );
	$timeout = cow_control_timeout_secs();

	if ( function_exists( 'curl_init' ) ) {
		$ch = curl_init( $url );
		curl_setopt( $ch, CURLOPT_POST, true );
		curl_setopt( $ch, CURLOPT_HTTPHEADER, array( 'Content-Type: application/json' ) );
		curl_setopt( $ch, CURLOPT_POSTFIELDS, $body );
		curl_setopt( $ch, CURLOPT_RETURNTRANSFER, true );
		curl_setopt( $ch, CURLOPT_CONNECTTIMEOUT, min( 3, $timeout ) );
		curl_setopt( $ch, CURLOPT_TIMEOUT, $timeout );
		$raw = curl_exec( $ch );
		$error = curl_error( $ch );
		curl_close( $ch );
		if ( false === $raw ) {
			return array( 'ok' => false, 'error' => $error );
		}
	} else {
		$context = stream_context_create(
			array(
				'http' => array(
					'method'  => 'POST',
					'header'  => "Content-Type: application/json\r\n",
					'content' => $body,
					'timeout' => $timeout,
				),
			)
		);
		$raw = @file_get_contents( $url, false, $context );
		if ( false === $raw ) {
			return array( 'ok' => false, 'error' => 'wp-cow control request failed' );
		}
	}

	$decoded = json_decode( $raw, true );
	if ( ! is_array( $decoded ) ) {
		return array( 'ok' => false, 'error' => 'invalid wp-cow control response' );
	}
	return $decoded;
}

class Cow_DB extends wpdb {
	private $cow_remote_mysqli = null;
	private $cow_remote_failed = false;

	public function query( $query ) {
		if ( ! $query ) {
			return false;
		}

		$this->flush();
		$this->last_query = $query;

		$tables = cow_tables_from_sql( $query );

		if ( cow_is_write_sql( $query ) ) {
			$result = cow_control_request( '/materialize', array( 'tables' => $tables ) );
			if ( empty( $result['ok'] ) ) {
				$this->last_error = isset( $result['error'] ) ? $result['error'] : 'wp-cow materialization failed';
				return false;
			}
			return parent::query( $query );
		}

		if ( cow_is_safe_read_sql( $query ) ) {
			$route = cow_control_request( '/route', array( 'tables' => $tables ) );
			if ( ! empty( $route['ok'] ) && isset( $route['backend'] ) && 'remote' === $route['backend'] ) {
				return $this->cow_remote_query( $query );
			}
			if ( ! empty( $route['ok'] ) && isset( $route['backend'] ) && 'local' === $route['backend'] ) {
				return parent::query( $query );
			}
		}

		return parent::query( $query );
	}

	private function cow_remote_query( $query ) {
		$remote = $this->cow_remote_mysqli();
		if ( $remote instanceof mysqli ) {
			$result = $remote->query( $query, MYSQLI_STORE_RESULT );
			if ( false === $result ) {
				$this->last_error = $remote->error;
				return false;
			}

			$this->last_result = array();
			$this->col_info = array();

			if ( true === $result ) {
				$this->num_rows = 0;
				$this->rows_affected = (int) $remote->affected_rows;
				$this->insert_id = (int) $remote->insert_id;
				$this->last_error = '';
				return $this->rows_affected;
			}

			foreach ( $result->fetch_fields() as $field ) {
				$this->col_info[] = (object) array( 'name' => $field->name );
			}
			while ( $row = $result->fetch_assoc() ) {
				$this->last_result[] = (object) $row;
			}
			$this->num_rows = count( $this->last_result );
			$this->rows_affected = $this->num_rows;
			$this->insert_id = (int) $remote->insert_id;
			$this->last_error = '';

			return $this->num_rows;
		}

		$result = cow_control_request( '/query', array( 'sql' => $query ) );
		if ( empty( $result['ok'] ) ) {
			$this->last_error = isset( $result['error'] ) ? $result['error'] : 'wp-cow remote query failed';
			return false;
		}

		$this->last_result = array();
		if ( isset( $result['rows'] ) && is_array( $result['rows'] ) ) {
			foreach ( $result['rows'] as $row ) {
				$this->last_result[] = (object) $row;
			}
		}

		$this->col_info = array();
		if ( isset( $result['fields'] ) && is_array( $result['fields'] ) ) {
			foreach ( $result['fields'] as $field ) {
				$this->col_info[] = (object) array( 'name' => $field );
			}
		}

		$this->num_rows = count( $this->last_result );
		$this->rows_affected = isset( $result['affected'] ) ? (int) $result['affected'] : $this->num_rows;
		$this->last_error = '';

		return $this->num_rows;
	}

	private function cow_remote_mysqli() {
		if ( $this->cow_remote_mysqli instanceof mysqli ) {
			return $this->cow_remote_mysqli;
		}
		if ( $this->cow_remote_failed ) {
			return null;
		}
		if ( '0' === getenv( 'WPCOW_REMOTE_DB_TUNNEL' ) ) {
			$this->cow_remote_failed = true;
			return null;
		}

		if (
			! defined( 'WPCOW_REMOTE_DB_NAME' ) ||
			! defined( 'WPCOW_REMOTE_DB_USER' ) ||
			! defined( 'WPCOW_REMOTE_DB_HOST' ) ||
			'' === WPCOW_REMOTE_DB_NAME ||
			'' === WPCOW_REMOTE_DB_USER
		) {
			return null;
		}

		$host = WPCOW_REMOTE_DB_HOST;
		$port = null;
		$socket = null;
		if ( preg_match( '/^(.+):([0-9]+)$/', $host, $matches ) ) {
			$host = $matches[1];
			$port = (int) $matches[2];
		} elseif ( preg_match( '/^([^:]+):(\/.*)$/', $host, $matches ) ) {
			$host = $matches[1];
			$socket = $matches[2];
		}

		$mysqli = mysqli_init();
		if ( ! $mysqli ) {
			$this->cow_remote_failed = true;
			return null;
		}

		@$mysqli->options( MYSQLI_OPT_CONNECT_TIMEOUT, 2 );
		if ( ! @$mysqli->real_connect( $host, WPCOW_REMOTE_DB_USER, WPCOW_REMOTE_DB_PASSWORD, WPCOW_REMOTE_DB_NAME, $port, $socket ) ) {
			$this->cow_remote_failed = true;
			return null;
		}

		@$mysqli->set_charset( $this->charset ? $this->charset : 'utf8mb4' );
		$this->cow_remote_mysqli = $mysqli;
		return $this->cow_remote_mysqli;
	}
}

$wpdb = new Cow_DB( DB_USER, DB_PASSWORD, DB_NAME, DB_HOST );
"#
}

pub fn safety_mu_plugin_php() -> &'static str {
    r#"<?php
/**
 * Generated by wp-cow. Disables common clone side effects.
 */

add_filter( 'pre_wp_mail', '__return_false' );

add_action(
	'send_headers',
	static function () {
		header( 'X-Robots-Tag: noindex, nofollow', true );
	}
);

if ( ! defined( 'DISABLE_WP_CRON' ) ) {
	define( 'DISABLE_WP_CRON', true );
}

add_filter( 'pre_http_request', static function ( $preempt, $args, $url ) {
	if ( defined( 'WPCOW_ALLOW_OUTBOUND_HTTP' ) && WPCOW_ALLOW_OUTBOUND_HTTP ) {
		return $preempt;
	}

	return new WP_Error( 'wp_cow_blocked_http', 'Outbound HTTP is blocked in this wp-cow clone.' );
}, 10, 3 );
"#
}

pub fn router_php() -> &'static str {
    r#"<?php
$path = parse_url( $_SERVER['REQUEST_URI'], PHP_URL_PATH );
$file = rtrim( $_SERVER['DOCUMENT_ROOT'], '/' ) . $path;

if ( '/' !== $path && is_file( $file ) ) {
	return false;
}

require rtrim( $_SERVER['DOCUMENT_ROOT'], '/' ) . '/index.php';
"#
}

fn php_string(value: &str) -> String {
    format!("'{}'", value.replace('\\', "\\\\").replace('\'', "\\'"))
}

