    fn http_get(port: u16, path: &str, timeout: Duration) -> std::io::Result<String> {
        let mut stream = TcpStream::connect(("127.0.0.1", port))?;
        stream.set_read_timeout(Some(timeout))?;
        stream.set_write_timeout(Some(timeout))?;
        write!(
            stream,
            "GET {path} HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\n\r\n"
        )?;

        let mut response = String::new();
        stream.read_to_string(&mut response)?;
        Ok(response)
    }

    fn http_get_nonempty(port: u16, path: &str, timeout: Duration) -> String {
        let started = Instant::now();
        loop {
            match http_get(port, path, Duration::from_millis(500)) {
                Ok(response) if !response.is_empty() => return response,
                Ok(_) | Err(_) if started.elapsed() < timeout => {
                    thread::sleep(Duration::from_millis(50));
                }
                Ok(response) => panic!("empty response from {path}: {response}"),
                Err(err) => panic!("request {path} failed: {err}"),
            }
        }
    }

    fn http_get_with_headers(
        port: u16,
        path: &str,
        headers: &[(&str, &str)],
        timeout: Duration,
    ) -> String {
        http_request(port, "GET", path, headers, "", timeout)
            .unwrap_or_else(|err| panic!("GET {path} failed: {err}"))
    }

    fn http_post(port: u16, path: &str, body: &str, timeout: Duration) -> String {
        http_request(
            port,
            "POST",
            path,
            &[("Content-Type", "application/x-www-form-urlencoded")],
            body,
            timeout,
        )
        .unwrap_or_else(|err| panic!("POST {path} failed: {err}"))
    }

    fn http_request(
        port: u16,
        method: &str,
        path: &str,
        headers: &[(&str, &str)],
        body: &str,
        timeout: Duration,
    ) -> std::io::Result<String> {
        let mut stream = TcpStream::connect(("127.0.0.1", port))?;
        stream.set_read_timeout(Some(timeout))?;
        stream.set_write_timeout(Some(timeout))?;
        let mut request = format!(
            "{method} {path} HTTP/1.1\r\nHost: 127.0.0.1\r\nConnection: close\r\nContent-Length: {}\r\n",
            body.len()
        );
        for (name, value) in headers {
            request.push_str(&format!("{name}: {value}\r\n"));
        }
        request.push_str("\r\n");
        request.push_str(body);
        stream.write_all(request.as_bytes())?;

        let mut response = String::new();
        stream.read_to_string(&mut response)?;
        Ok(response)
    }

    fn response_cookie(response: &str) -> Option<String> {
        response.lines().find_map(|line| {
            let (name, value) = line.split_once(':')?;
            if !name.eq_ignore_ascii_case("set-cookie") {
                return None;
            }
            value.trim().split(';').next().map(str::to_string)
        })
    }

    fn prepend_path(dir: &Path, old_path: Option<&OsString>) -> String {
        match old_path {
            Some(old) if !old.is_empty() => format!("{}:{}", dir.display(), old.to_string_lossy()),
            _ => dir.display().to_string(),
        }
    }

